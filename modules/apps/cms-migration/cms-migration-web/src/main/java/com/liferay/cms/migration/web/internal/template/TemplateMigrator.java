/**
 * Turns the Web Content templates of every migrated structure into
 * information templates of the object definition that replaces the
 * structure. The original FreeMarker code is kept; a generated preamble gives
 * it the variables that Web Content templates expect.
 *
 * @author Lino Alves
 */
public class TemplateMigrator {

	public TemplateMigrator(
		DDMTemplateLocalService ddmTemplateLocalService,
		InfoItemReferenceMapper infoItemReferenceMapper, Portal portal,
		TemplateEntryLocalService templateEntryLocalService) {

		_ddmTemplateLocalService = ddmTemplateLocalService;
		_infoItemReferenceMapper = infoItemReferenceMapper;
		_portal = portal;
		_templateEntryLocalService = templateEntryLocalService;
	}

	public String getScript(
		DDMStructure ddmStructure, DDMTemplate ddmTemplate) {

		String settings = JSONUtil.put(
			"ddmForm", ddmStructure.getDefinition()
		).put(
			"ddmStructureClassNameId",
			_portal.getClassNameId(DDMStructure.class)
		).put(
			"ddmStructureId", ddmStructure.getStructureId()
		).put(
			"ddmStructureKey", ddmStructure.getStructureKey()
		).put(
			"ddmTemplateId", ddmTemplate.getTemplateId()
		).put(
			"ddmTemplateKey", ddmTemplate.getTemplateKey()
		).put(
			"templateGroupId", ddmTemplate.getGroupId()
		).toString();

		StringBundler sb = new StringBundler();

		sb.append("<#-- Generated by the CMS migration from the Web Content ");
		sb.append("template ");
		sb.append(ddmTemplate.getTemplateKey());
		sb.append(". The lines up to the end marker give the original ");
		sb.append("template code the variables that Web Content templates ");
		sb.append("expect. -->\n");
		sb.append("<#if cmsMigrationTemplateContextHelper?? && ");
		sb.append("objectEntryId??>\n");
		sb.append("\t<#assign cmsMigrationContext = ");
		sb.append("cmsMigrationTemplateContextHelper.getContext(");
		sb.append("objectEntryId.getData(), \"");
		sb.append(
			Base64.getEncoder(
			).encodeToString(
				settings.getBytes(StandardCharsets.UTF_8)
			));
		sb.append("\") />\n");

		for (String name : _getVariableNames(ddmStructure)) {
			sb.append("\t<#assign \"");
			sb.append(name);
			sb.append("\" = cmsMigrationContext[\"");
			sb.append(name);
			sb.append("\"]! />\n");
		}

		sb.append("</#if>\n");
		sb.append("<#-- End of the CMS migration context -->\n");
		sb.append("<div class=\"journal-content-article\">");
		sb.append(_replaceTokens(ddmTemplate.getScript()));
		sb.append("</div>");

		return sb.toString();
	}

	public void migrate(CMSMigrationContext cmsMigrationContext) {
		for (DDMStructure ddmStructure :
				new ArrayList<>(cmsMigrationContext.getDDMStructures())) {

			migrate(cmsMigrationContext, ddmStructure);
		}
	}

	/**
	 * Migrates the templates of one structure, unless they were already
	 * migrated. References to a structure that has no content, such as its
	 * display page templates, register the structure after the templates
	 * phase, so they call this method to migrate its templates on demand.
	 */
	public void migrate(
		CMSMigrationContext cmsMigrationContext, DDMStructure ddmStructure) {

		ObjectDefinition objectDefinition =
			cmsMigrationContext.getObjectDefinition(
				JournalArticle.class.getName(), ddmStructure.getStructureId());

		if ((objectDefinition == null) ||
			!cmsMigrationContext.addTemplateDDMStructureId(
				ddmStructure.getStructureId())) {

			return;
		}

		List<DDMTemplate> ddmTemplates = Collections.emptyList();

		try {
			ddmTemplates = _ddmTemplateLocalService.getTemplates(
				cmsMigrationContext.getSourceGroupId(),
				_portal.getClassNameId(DDMStructure.class),
				ddmStructure.getStructureId(), true);
		}
		catch (PortalException portalException) {
			cmsMigrationContext.getCMSMigrationReport(
			).addError(
				StringBundler.concat(
					"Unable to get the templates of the structure ",
					ddmStructure.getStructureKey(), ": ",
					portalException.getMessage())
			);
		}

		for (DDMTemplate ddmTemplate : ddmTemplates) {
			cmsMigrationContext.sendStatus(ddmTemplate.getTemplateKey());

			try {
				_migrate(
					cmsMigrationContext, ddmStructure, ddmTemplate,
					objectDefinition);
			}
			catch (Exception exception) {
				cmsMigrationContext.getCMSMigrationReport(
				).addError(
					StringBundler.concat(
						"Unable to migrate the template ",
						ddmTemplate.getTemplateKey(), ": ",
						exception.getMessage())
				);
			}
		}

		for (TemplateEntry templateEntry :
				_templateEntryLocalService.getTemplateEntries(
					cmsMigrationContext.getSourceGroupId(),
					JournalArticle.class.getName(),
					String.valueOf(ddmStructure.getStructureId()),
					QueryUtil.ALL_POS, QueryUtil.ALL_POS, null)) {

			try {
				_migrateInformationTemplate(
					cmsMigrationContext, ddmStructure, objectDefinition,
					templateEntry);
			}
			catch (Exception exception) {
				cmsMigrationContext.getCMSMigrationReport(
				).addError(
					StringBundler.concat(
						"Unable to migrate the information template ",
						templateEntry.getTemplateEntryId(), ": ",
						exception.getMessage())
				);
			}
		}
	}

	private TemplateEntry _addOrUpdateTemplateEntry(
			CMSMigrationContext cmsMigrationContext, DDMTemplate ddmTemplate,
			String externalReferenceCode, ObjectDefinition objectDefinition,
			String script)
		throws PortalException {

		TemplateEntry templateEntry =
			_templateEntryLocalService.
				fetchTemplateEntryByExternalReferenceCode(
					externalReferenceCode,
					cmsMigrationContext.getSourceGroupId());

		if (templateEntry != null) {
			DDMTemplate infoDDMTemplate =
				_ddmTemplateLocalService.getDDMTemplate(
					templateEntry.getDDMTemplateId());

			_ddmTemplateLocalService.updateTemplate(
				cmsMigrationContext.getUserId(),
				infoDDMTemplate.getTemplateId(), infoDDMTemplate.getClassPK(),
				ddmTemplate.getNameMap(), ddmTemplate.getDescriptionMap(),
				DDMTemplateConstants.TEMPLATE_TYPE_DISPLAY, StringPool.BLANK,
				TemplateConstants.LANG_TYPE_FTL, script,
				ddmTemplate.isCacheable(),
				cmsMigrationContext.getServiceContext());

			return templateEntry;
		}

		long templateEntryClassNameId = _portal.getClassNameId(
			TemplateEntry.class);

		DDMTemplate infoDDMTemplate = _ddmTemplateLocalService.addTemplate(
			externalReferenceCode, cmsMigrationContext.getUserId(),
			cmsMigrationContext.getSourceGroupId(), templateEntryClassNameId, 0,
			templateEntryClassNameId, ddmTemplate.getNameMap(),
			ddmTemplate.getDescriptionMap(),
			DDMTemplateConstants.TEMPLATE_TYPE_DISPLAY, StringPool.BLANK,
			TemplateConstants.LANG_TYPE_FTL, script,
			cmsMigrationContext.getServiceContext());

		return _templateEntryLocalService.addTemplateEntry(
			externalReferenceCode, cmsMigrationContext.getUserId(),
			cmsMigrationContext.getSourceGroupId(),
			infoDDMTemplate.getTemplateId(), objectDefinition.getClassName(),
			StringPool.BLANK, cmsMigrationContext.getServiceContext());
	}

	private String _getInformationTemplateScript(
		CMSMigrationContext cmsMigrationContext, DDMStructure ddmStructure,
		DDMTemplate ddmTemplate, ObjectDefinition objectDefinition) {

		String script = _replaceInformationTemplateVariables(
			cmsMigrationContext, ddmStructure, ddmTemplate, objectDefinition,
			_informationTemplateQuotedVariablePattern, ddmTemplate.getScript());

		script = _replaceInformationTemplateVariables(
			cmsMigrationContext, ddmStructure, ddmTemplate, objectDefinition,
			_informationTemplateVariablePattern, script);

		return StringBundler.concat(
			"<#-- Generated by the CMS migration from the information ",
			"template ", ddmTemplate.getTemplateKey(), ". -->\n", script);
	}

	private Set<String> _getVariableNames(DDMStructure ddmStructure) {
		Set<String> variableNames = new LinkedHashSet<>();

		DDMForm ddmForm = ddmStructure.getFullHierarchyDDMForm();

		_putFieldReferences(ddmForm.getDDMFormFields(), variableNames);

		Collections.addAll(variableNames, _RESERVED_VARIABLE_NAMES);

		return variableNames;
	}

	private void _migrate(
			CMSMigrationContext cmsMigrationContext, DDMStructure ddmStructure,
			DDMTemplate ddmTemplate, ObjectDefinition objectDefinition)
		throws PortalException {

		if (!Objects.equals(
				ddmTemplate.getLanguage(), TemplateConstants.LANG_TYPE_FTL)) {

			cmsMigrationContext.getCMSMigrationReport(
			).addWarning(
				"Skipped the template " + ddmTemplate.getTemplateKey() +
					" because only FreeMarker templates can be migrated"
			);

			return;
		}

		TemplateEntry templateEntry = _addOrUpdateTemplateEntry(
			cmsMigrationContext, ddmTemplate,
			CMSMigrationConstants.EXTERNAL_REFERENCE_CODE_PREFIX_DDM_TEMPLATE +
				ddmTemplate.getTemplateId(),
			objectDefinition, getScript(ddmStructure, ddmTemplate));

		cmsMigrationContext.addTemplateEntryId(
			ddmStructure.getStructureId(), ddmTemplate.getTemplateKey(),
			templateEntry.getTemplateEntryId());

		cmsMigrationContext.getCMSMigrationReport(
		).increment(
			CMSMigrationConstants.PHASE_TEMPLATES
		);
	}

	private void _migrateInformationTemplate(
			CMSMigrationContext cmsMigrationContext, DDMStructure ddmStructure,
			ObjectDefinition objectDefinition, TemplateEntry templateEntry)
		throws PortalException {

		DDMTemplate ddmTemplate = _ddmTemplateLocalService.getDDMTemplate(
			templateEntry.getDDMTemplateId());

		cmsMigrationContext.sendStatus(ddmTemplate.getTemplateKey());

		if (!Objects.equals(
				ddmTemplate.getLanguage(), TemplateConstants.LANG_TYPE_FTL)) {

			cmsMigrationContext.getCMSMigrationReport(
			).addWarning(
				"Skipped the information template " +
					ddmTemplate.getTemplateKey() +
						" because only FreeMarker templates can be migrated"
			);

			return;
		}

		TemplateEntry newTemplateEntry = _addOrUpdateTemplateEntry(
			cmsMigrationContext, ddmTemplate,
			CMSMigrationConstants.EXTERNAL_REFERENCE_CODE_PREFIX_DDM_TEMPLATE +
				ddmTemplate.getTemplateId(),
			objectDefinition,
			_getInformationTemplateScript(
				cmsMigrationContext, ddmStructure, ddmTemplate,
				objectDefinition));

		cmsMigrationContext.addInformationTemplateEntryId(
			templateEntry.getTemplateEntryId(),
			newTemplateEntry.getTemplateEntryId());

		cmsMigrationContext.getCMSMigrationReport(
		).increment(
			CMSMigrationConstants.PHASE_TEMPLATES
		);
	}

	private void _putFieldReferences(
		List<DDMFormField> ddmFormFields, Set<String> fieldReferences) {

		for (DDMFormField ddmFormField : ddmFormFields) {
			fieldReferences.add(ddmFormField.getFieldReference());

			_putFieldReferences(
				ddmFormField.getNestedDDMFormFields(), fieldReferences);
		}
	}

	private String _replaceInformationTemplateVariables(
		CMSMigrationContext cmsMigrationContext, DDMStructure ddmStructure,
		DDMTemplate ddmTemplate, ObjectDefinition objectDefinition,
		Pattern pattern, String script) {

		Matcher matcher = pattern.matcher(script);

		StringBuffer sb = new StringBuffer();

		while (matcher.find()) {
			String fieldId = matcher.group(1);

			String newFieldId = _infoItemReferenceMapper.getFieldId(
				cmsMigrationContext, JournalArticle.class.getName(),
				ddmStructure, objectDefinition, fieldId, false);

			String replacement = matcher.group();

			if (newFieldId == null) {
				cmsMigrationContext.getCMSMigrationReport(
				).addWarning(
					StringBundler.concat(
						"The field ", fieldId, " of the information template ",
						ddmTemplate.getTemplateKey(), " has no counterpart in ",
						objectDefinition.getName())
				);
			}
			else if (!replacement.startsWith(".vars") &&
					 Validator.isVariableName(newFieldId)) {

				replacement = newFieldId;
			}
			else {
				replacement = ".vars[\"" + newFieldId + "\"]";
			}

			matcher.appendReplacement(
				sb, Matcher.quoteReplacement(replacement));
		}

		matcher.appendTail(sb);

		return sb.toString();
	}

	private String _replaceTokens(String script) {
		Matcher matcher = _tokenPattern.matcher(script);

		StringBuffer sb = new StringBuffer();

		while (matcher.find()) {
			String token = matcher.group(1);

			if (!_tokens.contains(token)) {
				matcher.appendReplacement(
					sb, Matcher.quoteReplacement(matcher.group()));

				continue;
			}

			matcher.appendReplacement(
				sb,
				Matcher.quoteReplacement(
					"${cmsMigrationTokens." + token + "}"));
		}

		matcher.appendTail(sb);

		return sb.toString();
	}

	private static final String[] _RESERVED_VARIABLE_NAMES = {
		"articleGroupId", "articleLocale", "cmsMigrationTokens", "groupId",
		"journalContent", "journalContentUtil", "journalTemplatesPath",
		"randomNamespace", "reserved-article-asset-tag-names",
		"reserved-article-author-comments",
		"reserved-article-author-email-address", "reserved-article-author-id",
		"reserved-article-author-job-title", "reserved-article-author-name",
		"reserved-article-create-date", "reserved-article-description",
		"reserved-article-display-date",
		"reserved-article-external-reference-code", "reserved-article-id",
		"reserved-article-id_", "reserved-article-modified-date",
		"reserved-article-resource-prim-key",
		"reserved-article-small-image-url", "reserved-article-title",
		"reserved-article-url-title", "reserved-article-version",
		"templatesPath", "viewMode"
	};

	private static final Pattern _informationTemplateQuotedVariablePattern =
		Pattern.compile(
			"\\.vars\\[\\s*\"((?:DDMStructure|JournalArticle)_[^\"]+)\"" +
				"\\s*\\]");
	private static final Pattern _informationTemplateVariablePattern =
		Pattern.compile("(?<![\\w.\"#])((?:DDMStructure|JournalArticle)_\\w+)");
	private static final Pattern _tokenPattern = Pattern.compile(
		"(?<!@)@([a-z_]+)@(?!@)");
	private static final Set<String> _tokens = new LinkedHashSet<>(
		List.of(
			"article_group_id", "article_resource_pk", "cdn_host",
			"class_name_id", "company_group_id", "company_id",
			"ddm_structure_id", "ddm_structure_key", "ddm_template_id",
			"ddm_template_key", "friendly_url_current",
			"friendly_url_private_group", "friendly_url_private_user",
			"friendly_url_public", "group_friendly_url", "image_path",
			"layout_set_friendly_url", "main_path", "portal_ctx", "portal_url",
			"protocol", "root_path", "scope_group_id", "site_group_id",
			"theme_image_path"));

	private final DDMTemplateLocalService _ddmTemplateLocalService;
	private final InfoItemReferenceMapper _infoItemReferenceMapper;
	private final Portal _portal;
	private final TemplateEntryLocalService _templateEntryLocalService;

}